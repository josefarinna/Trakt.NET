        [Theory]
        [InlineData(null, null, null, null, null, null, GetRecentlyUpdatedCommentsUri)]
        [InlineData(CommentType, null, null, null, null, null, $"{GetRecentlyUpdatedCommentsUri}/shouts")]
        [InlineData(null, ObjectType, null, null, null, null, $"{GetRecentlyUpdatedCommentsUri}/episodes")]
        [InlineData(null, null, true, null, null, null, $"{GetRecentlyUpdatedCommentsUri}?include_replies=true")]
        [InlineData(null, null, null, ExtendedInfo, null, null, $"{GetRecentlyUpdatedCommentsUri}?extended=full")]
        [InlineData(null, null, null, null, Page, null, $"{GetRecentlyUpdatedCommentsUri}?page=2")]
        [InlineData(null, null, null, null, null, Limit, $"{GetRecentlyUpdatedCommentsUri}?limit=4")]
        [InlineData(CommentType, ObjectType, true, ExtendedInfo, Page, Limit, $"{GetRecentlyUpdatedCommentsUri}/shouts/episodes" + $"?include_replies=true&extended=full&page=2&limit=4")]
        public async Task TestGetRecentlyUpdatedComments(TraktCommentType? commentType, TraktCommentObjectType? type, bool? includeReplies, TraktExtendedInfo? extendedInfo, uint? page, uint? limit, string requestUri)
        {
            string responseContent = await TestUtility.GetJsonFileContentAsync("Comments\\comments.json");

            TraktClient client = ModuleTestUtility.GetClient(requestUri, responseContent, page, 1, limit, CommentsItemCount);

            TraktPagedResponse<TraktUserComment> response = await client.Comments.GetRecentlyUpdatedCommentsAsync(commentType, type, includeReplies, extendedInfo, page, limit, TestContext.Current.CancellationToken);

            response.ShouldNotBeNull();
            response.IsSuccess.ShouldBeTrue();
            response.HasValue.ShouldBeTrue();
            response.Content.ShouldNotBeNull();
            response.Content.Count.ShouldBe((int)CommentsItemCount);
            response.ItemCount.ShouldBe(CommentsItemCount);
            response.Limit.ShouldBe(limit ?? 10U);
            response.Page.ShouldBe(page ?? 1U);
            response.PageCount.ShouldBe(1U);
        }

